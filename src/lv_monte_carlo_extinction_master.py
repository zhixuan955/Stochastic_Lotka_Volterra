# ----------------------------------------------------------------------------------------------------------------------
# Import libraries
# ----------------------------------------------------------------------------------------------------------------------
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import csv

# ----------------------------------------------------------------------------------------------------------------------
# Global Parameters
# ----------------------------------------------------------------------------------------------------------------------
alpha, beta, gamma, delta = 0.1, 0.0004, 0.15, 0.00035      # growth-rate-affecting parameters
K, h = 5000, 0.45                                           # carrying capacity (K) and predator handling time (h)
x0, y0 = 1000, 500                                          # starting population values
t_end, dt = 250, 0.01                                       # Total time frame and step increment
n_steps = int(t_end / dt)                                   # Number of steps
N = 5000                                                    # runs per noise level
THRESH = 1.0                                                # quasi-extinction threshold (individuals) = if population value dips below 1
sigma_ratio = 0.7                                           # sigma_y = ratio * sigma_x (original: 0.035/0.05)
sigmas = [0.0, 0.05, 0.10, 0.15, 0.20, 0.25, 0.30, 0.40, 0.50]
# Testing out with a range of values for sigma, which will determine the value of multiplicative noise

# ----------------------------------------------------------------------------------------------------------------------
# Deterministic drift term of the SDE
# ----------------------------------------------------------------------------------------------------------------------
def deterministic_drift(x, y):
    # prey and predator equations taken from previous model
    functional_response = 1 + beta * h * x

    # computing prey and predator growth rate
    dxdt = alpha*x*(1 - x / K) - (beta*x*y/functional_response)
    dydt = (delta*x*y/functional_response) - gamma * y

    return dxdt, dydt

# ----------------------------------------------------------------------------------------------------------------------
# Wilson confidence interval
# ----------------------------------------------------------------------------------------------------------------------
def wilson(extinct, n, z=1.96):
    # z = 1.96 because targeting 95% confidence level
    osp = extinct / n
    # Observed Sample Proportion (number of simulations that go into extinctions/total sims)

    # Using symmetry in the roots:
    centre = (osp + z**2/(2 * n)) / (1 + z**2/n)
    half_width = z * (np.sqrt(osp * (1 - osp)/n + (z**2/(4 * n**2)) ) ) / (1 + z**2/n)

    return max(0, centre - half_width), min(1, centre + half_width)
    # This ensures probability values remains within the bounds of [0, 1]

# ----------------------------------------------------------------------------------------------------------------------
# Solving the system and counting extinction realisations
# ----------------------------------------------------------------------------------------------------------------------
def run(sx):
    # computing sigma value for predators
    sy = sigma_ratio * sx

    # Setup
    x = np.full(N, float(x0)); y = np.full(N, float(y0))
    ext_prey = np.full(N, np.nan); ext_pred = np.full(N, np.nan)
    # nan represents absence of extinction event
    alive_x = np.ones(N, bool); alive_y = np.ones(N, bool)

    # Employing Euler-Maruyama
    for i in range(n_steps):

        dx, dy = deterministic_drift(x, y)

        # Since noise here is computed every iteration with normal distribution, slight variations in results are expected
        # A set seed generated by a random number generator will reproduce the same results every time
        x = x + dx * dt + (sx * x * np.random.normal(0, np.sqrt(dt), N))
        y = y + dy * dt + (sy * y * np.random.normal(0, np.sqrt(dt), N))

        # Prevents populations from becoming negative
        x = np.maximum(x, 0); y = np.maximum(y, 0)

        # Detects when populations go below 1 and counts them
        threshold_x = alive_x & (x < THRESH); threshold_y = alive_y & (y < THRESH)
        # This records the time at which quasi-extinction threshold is reached
        ext_prey[threshold_x] = (i + 1) * dt; ext_pred[threshold_y] = (i + 1) * dt
        alive_x &= ~threshold_x; alive_y &= ~threshold_y
        # If both populations are zero, then system freezes, so stops when extinction reached
        x[~alive_x] = 0; y[~alive_y] = 0

    return ext_prey, ext_pred

# ----------------------------------------------------------------------------------------------------------------------
# Interpreting data
# ----------------------------------------------------------------------------------------------------------------------
# This sets up a record of the data collected at each noise level
# Each noise level collects the data down in the print statement
rows = []

# Iterating through every value of sigma from the global list
# N.B. - x refers to prey, y refers to predator
for sx in sigmas:
    ext_time_x, ext_time_y = run(sx)
    extinct_x, extinct_y = np.isfinite(ext_time_x).sum(), np.isfinite(ext_time_y).sum()
    extinct_any = (np.isfinite(ext_time_x) | np.isfinite(ext_time_y)).sum()

    x_low, x_high = wilson(extinct_x, N)
    y_low, y_high = wilson(extinct_y, N)
    any_low, any_high = wilson(extinct_any, N)


    # Compiling probability data into a dictionary
    record = dict(sigma_x=sx, sigma_y=round(sigma_ratio * sx, 4),
                  P_x = extinct_x/N, P_y = extinct_y/N, P_any = extinct_any/N,
                  x_low = x_low, x_high = x_high,
                  y_low = y_low, y_high = y_high,
                  any_low = any_low, any_high = any_high,

                # Calculating median extinction time, ignoring any NaNs
                  median_T_x = np.nanmedian(ext_time_x) if extinct_x else np.nan,
                  median_T_y = np.nanmedian(ext_time_y) if extinct_y else np.nan)

    rows.append(record)

    # printing: sigma to 2 s.f., probabilities of extinction of populations (prey, predator, either),
    # and median time needed to reach extinction
    print(f"sx={sx:.2f}  P(prey)={record['P_x']:.4f}  P(pred)={record['P_y']:.4f}  "
          f"P(any)={record['P_any']:.4f}  medT_pred={record['median_T_y']:.1f}", flush=True)

# writing results into a csv file
with open("extinction_results.csv", "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=rows[0].keys()); w.writeheader(); w.writerows(rows)

# ----------------------------------------------------------------------------------------------------------------------
# Plotting the graph to relate sigma to extinction probability
# ----------------------------------------------------------------------------------------------------------------------
sigma_axis = np.array([r["sigma_x"] for r in rows])
fig, ax = plt.subplots(figsize=(9, 6))

for key, label, color in [("x", "y", "steelblue"), ("x", "y", "darkorange"), ("any", "Either", "k")]:
    p = np.array([r[f"P_{key}"] for r in rows])

    low = np.array([r[f"{key}_low"] for r in rows])
    high = np.array([r[f"{key}_high"] for r in rows])

    ax.plot(sigma_axis, p, "o-", color=color, label=label)
    ax.fill_between(sigma_axis, low, high, color=color, alpha=0.2)

# The labels of the plot
# Dollar signs ($) used to denote mathematical notation
ax.set_xlabel(r"Prey noise $\sigma_x$ ($\sigma_y = 0.7\sigma_x$)")      # using r (raw string) for math notation
ax.set_ylabel(f"P(quasi-extinction by t={t_end}, threshold<{THRESH:g})")
# Title of the plot
ax.set_title(f"Extinction probability vs multiplicative noise (N={N} per level, 95% Wilson CI)")
# Legend of the plot
ax.legend(); ax.grid(alpha=0.3); fig.tight_layout()

# saving the plot as a png
fig.savefig("extinction_vs_noise.png", dpi=150)

# ----------------------------------------------------------------------------------------------------------------------
# For reference, deterministic model values
# ----------------------------------------------------------------------------------------------------------------------
x, y = float(x0), float(y0)

# empty list used to track the minimum value
xs = []
for i in range(n_steps):
    dx, dy = deterministic_drift(x, y)
    x += dx * dt; y += dy * dt
    xs.append((x, y))

final_x, final_y = xs[-1]
min_x = min(a for a, b in xs)
min_y = min(b for a, b in xs)

print(f"deterministic end state: prey={final_x:.1f}, predator={final_y:.1f}")
print(f"deterministic minima:    prey={min_x:.1f}, predator={min_y:.1f}")